//! Internationalization foundation for `syssur-app`.
//! Structured around strongly-typed `TextKey`s so new languages (or Fluent `.ftl`
//! bundles) can be added without touching UI widget code.

#[derive(Clone, Copy, Debug, PartialEq, Eq, Default)]
pub enum Locale {
    #[default]
    En,
    Fr,
}

impl Locale {
    pub const ALL: [Self; 2] = [Self::En, Self::Fr];

    pub fn display_name(self) -> &'static str {
        match self {
            Self::En => "English",
            Self::Fr => "Français",
        }
    }
}

